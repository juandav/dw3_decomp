s32 func_800A4CA8(StageTileAnim *obj, AnimFrame *frames, s32 depth) {
    AnimFrame *frame = &frames[obj->anim.index];
    s32 dt = GFX_FUNCS.getFrameTime();

    if (dt > 4) {
        dt = 4;
    }
    if (depth == 0) {
        obj->anim.timer -= dt;
    }
    if (obj->anim.timer <= 0) {
        frame++;
        obj->anim.index++;
        obj->anim.timer += frame->duration;
        if (frame->frame == 0xFF) {
            return 0xFF;
        }
        func_800A4CA8(obj, frames, depth + 1);
    }
    return frame->frame;
}

/* Plays the animation of the record with animation 1 once with a sound when the substate is 0, then kills itself */
void func_800A4D80(StageTileTask *task) {
    StageTile *rec;
    StageTile *tile;
    s32 frame;

    switch (task->state) {
    case TASK_INIT:
    default:
        task->nextState(task);
        task->obj.anim.index = 0;
        task->obj.anim.timer = D_800A5234[0].duration;
        for (rec = D_800990B4.unk10; rec->unk2 != 0; rec++) {
            if (rec->anim == 1) {
                task->obj.tile = rec;
            }
        }
        break;
    case TASK_RUN:
        if (task->substate == 0) {
            task->obj.anim.index = 0;
            task->obj.anim.timer = D_800A5234[0].duration;
            task->setSubstate(task, 1);
            SOUND.playSound(0x8004213E);
        }
        tile = task->obj.tile;
        frame = func_800A4CA8(&task->obj, D_800A5234, 0);
        if (frame == 0xFF) {
            tile->visible = 0;
            task->setState(task, TASK_KILL);
        } else {
            tile->visible = 1;
            tile->frame = frame;
        }
        break;
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

